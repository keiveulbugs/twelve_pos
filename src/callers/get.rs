use crate::callers::RequestError;

/// Builder for Get Requests
#[must_use = "GetRequestBuilder needs to be `.send()` for it to return a response."]
pub struct GetRequestBuilder {
    twelveclient: crate::TwelveClient,
    path: String,
    query: Option<String>,
    additional_headers: Vec<(reqwest::header::HeaderName, reqwest::header::HeaderValue)>,
}

impl crate::callers::Callers<'_> {
    pub fn get(&self, path: impl Into<String>) -> GetRequestBuilder {
        GetRequestBuilder {
            twelveclient: self.twelveclient.clone(),
            path: path.into(),
            query: None,
            additional_headers: Vec::new(),
        }
    }
}

impl GetRequestBuilder {
    pub fn query(mut self, query: impl Into<String>) -> GetRequestBuilder {
        self.query = Some(query.into());
        self
    }
    pub fn additional_headers(
        mut self,
        headers: Vec<(reqwest::header::HeaderName, reqwest::header::HeaderValue)>,
    ) -> GetRequestBuilder {
        self.additional_headers = headers;
        self
    }
    pub async fn send(&self) -> Result<reqwest::Response, RequestError> {
        let mut url = self.twelveclient.config().url().clone();
        url.set_path(&self.path);
        url.set_query(self.query.as_deref());

        let mut headermap = self.twelveclient.config().generate_headermap(&self.path)?;

        for (key, val) in &self.additional_headers {
            let headermap_option = headermap
                .try_insert(key, val.clone())
                .map_err(|_| RequestError::ExceededCapacity)?;

            // This returns the function when the user accidentally or on purpose replaces the headers generated by the crate.
            // This is considered an error to avoid users accidentally leaking secrets.
            if headermap_option.is_some() {
                return Err(RequestError::InvalidHeaders(key.to_string()));
            }
        }

        let requestbuilder = self
            .twelveclient
            .network_client
            .get(url.clone())
            .headers(headermap);

        let response = requestbuilder.send().await?;

        Ok(response)
    }
}
